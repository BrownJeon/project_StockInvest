import { NextRequest, NextResponse } from 'next/server';
import type { ResultSetHeader, RowDataPacket } from 'mysql2';
import { getPool } from '@/lib/db';
import { databaseId, requireChatUser } from '@/lib/chat/ownership';

export const dynamic = 'force-dynamic';

export async function GET(req: NextRequest) {
  const auth = await requireChatUser(req);
  if (!auth.ok) return auth.res;
  const archived = req.nextUrl.searchParams.get('archived') === '1';
  const pool = getPool();
  const [rows] = await pool.query<RowDataPacket[]>(
    `SELECT t.id, t.title, t.symbol, t.created_at, t.updated_at, t.message_count, t.archived
     FROM chat_threads t INNER JOIN users u ON u.id = t.user_id
     WHERE t.archived = ? AND t.user_id = ?
     ORDER BY t.updated_at DESC LIMIT 200`,
    [archived ? 1 : 0, auth.userId],
  );
  // This API currently returns numeric IDs. Never round a DB BIGINT.
  if (rows.some(r => databaseId(r.id) === null)) {
    return NextResponse.json({ ok: false, error: 'unsafe identifier' }, { status: 503 });
  }
  return NextResponse.json({
    ok: true,
    threads: rows.map(r => ({
      id:           databaseId(r.id),
      title:        r.title as string,
      symbol:       r.symbol ?? null,
      createdAt:    r.created_at,
      updatedAt:    r.updated_at,
      messageCount: Number(r.message_count),
      archived:     Boolean(r.archived),
    })),
  });
}

export async function POST(req: NextRequest) {
  const auth = await requireChatUser(req);
  if (!auth.ok) return auth.res;
  const body = await req.json().catch(() => ({}));
  const title = typeof body?.title === 'string' && body.title.trim().length > 0 ? body.title.trim().slice(0, 120) : '새 대화';
  const symbol = typeof body?.symbol === 'string' ? body.symbol.slice(0, 32) : null;
  const pool = getPool();
  // IDs are generated by the DB: validate before commit so a too-large ID
  // cannot leave an inaccessible row in the current numeric-ID API.
  const connection = await pool.getConnection();
  try {
    await connection.beginTransaction();
    const [res] = await connection.query<ResultSetHeader>(
      'INSERT INTO chat_threads (title, symbol, user_id) SELECT ?, ?, u.id FROM users u WHERE u.id = ?',
      [title, symbol, auth.userId],
    );
    if (res.affectedRows !== 1) {
      await connection.rollback();
      return NextResponse.json({ ok: false, error: 'unauthorized' }, { status: 401 });
    }
    const id = databaseId(res.insertId);
    if (id === null) {
      await connection.rollback();
      return NextResponse.json({ ok: false, error: 'unsafe identifier' }, { status: 503 });
    }
    await connection.commit();
    return NextResponse.json({ ok: true, id });
  } catch (error) {
    await connection.rollback();
    throw error;
  } finally {
    connection.release();
  }
}
