/**
 * 알림 본문 엔티티 이스케이프 (T-010 reviewer MEDIUM 후속, 2026-08-09).
 *
 * **새로 만든 규칙이 아니다** — T-004 때 `telegram.ts` 의 `mrkdwnToTelegramHtml` 안에 있던
 * 엔티티 이스케이프 절반을 여기로 **추출**한 것이다. `mrkdwnToTelegramHtml` 은 이제 이 함수를
 * 호출해 앞부분을 처리한다. 구현은 하나뿐이고 소비자가 둘이다.
 *
 * ## 왜 추출했나
 *
 * `dispatchAlert(level, title, body)` 는 같은 `body` 를 두 채널에 **그대로** 꽂는다:
 *   - `telegram.ts` → `parse_mode:'HTML'`. `<a href="…">` 가 실제 링크로 렌더된다
 *   - `slack.ts`    → `type:'mrkdwn'`.     `<url|텍스트>` 가 실제 링크로 렌더된다
 *
 * 알림 본문 대부분은 우리가 만든 문자열이라 문제가 없었지만, T-010 의 가입 요청 폴백은
 * **외부인이 입력한 값**(이름·이메일·하실 말씀)을 싣는다. 이스케이프 없이 보내면:
 *
 *   1. **피싱** — 요청자가 고른 문구의 클릭 가능한 링크가 관리자 알림에 렌더된다.
 *      그 알림을 받는 사람이 증권계좌 자격증명을 쥐고 있다
 *   2. **조용한 유실** — 짝이 안 맞는 `<` 하나만 있어도 텔레그램이 HTTP 400 으로 거절한다.
 *      폴백은 "메일이 실패했을 때 관리자가 요청을 놓치지 않게" 하는 마지막 방어선인데,
 *      그게 사용자 입력 한 글자로 깨진다 — T-007 이 잡았던 실패 유형 그대로다.
 *
 * ## 왜 채널별로 나누지 않는가
 *
 * 텔레그램 HTML 과 슬랙 mrkdwn 은 **똑같이 `&`·`<`·`>` 세 글자**만 escape 하면 된다
 * (슬랙 규정: `&`→`&amp;`, `<`→`&lt;`, `>`→`&gt;`). 그래서 함수 하나로 양쪽이 안전하고,
 * `dispatchAlert` 이 두 채널에 **같은 본문**을 보내는 구조와도 맞아떨어진다.
 *
 * ## 왜 전송 함수(telegram.ts/slack.ts) 안에서 일괄 처리하지 않는가
 *
 * `telegram.ts` 주석이 이미 그 이유를 못박아 뒀다 — holding-checker 처럼 본문에 `<b>` 를
 * **의도적으로** 넣는 호출부가 있어서, 전송 함수가 일괄 escape 하면 그쪽 서식이 깨진다.
 * 따라서 **사용자 입력을 담는 호출부가 주입 지점에서** escape 하는 것이 이 코드베이스의 규약이다.
 *
 * ⚠️ 이 함수는 `*` 를 건드리지 않는다. 슬랙에서 `*강조*` 가 될 수 있지만 링크·멘션 같은
 *    구조를 만들지 못하고(피싱 벡터가 아니다), 사용자가 쓴 별표를 지우면 원문이 왜곡된다.
 */

/**
 * 텔레그램 HTML·슬랙 mrkdwn 양쪽에서 안전한 리터럴 텍스트로 만든다.
 *
 * **반드시 서식 변환보다 먼저** 적용해야 한다 — 나중에 적용하면 우리가 의도적으로 넣은
 * `<b>` 태그까지 같이 이스케이프된다(`mrkdwnToTelegramHtml` 이 이 순서를 지킨다).
 */
export function escapeAlertText(raw: unknown): string {
  if (typeof raw !== 'string') return '';
  return raw
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}
